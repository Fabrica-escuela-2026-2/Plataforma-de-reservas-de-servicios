package com.udea.service_platform.modules.reservations.migration;

import org.junit.jupiter.api.Test;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.time.Clock;
import java.time.Instant;
import java.time.ZoneId;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * HU-14: ReservaHoraInicioMigration ejecutada directamente (sin contexto de
 * Spring) sobre bases aisladas del PostgreSQL embebido, para cubrir cada
 * situacion de partida: base nueva, base ya migrada, esquema de main y una
 * base a medio crear.
 */
class ReservaHoraInicioMigrationTest {

    private static final ZoneId BOGOTA = ZoneId.of("America/Bogota");
    /** 2026-10-21 03:00 UTC = 2026-10-20 22:00 en Bogota: la fecha de la migracion debe ser la local (20). */
    private static final Clock RELOJ = Clock.fixed(Instant.parse("2026-10-21T03:00:00Z"), BOGOTA);

    private static final String CREAR_RESERVAS_DE_LA_RAMA = "CREATE TABLE \"Reservas\" ("
            + "id_reserva bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "estado_reserva integer NOT NULL, servicio_reserva bigint NOT NULL, usuario_reserva bigint NOT NULL, "
            + "hora_inicio timestamp(6) with time zone, valor_acordado numeric(38,2), duracion_acordada integer)";
    private static final String AGREGAR_HORA_INICIO_COMO_HIBERNATE =
            "ALTER TABLE \"Reservas\" ADD COLUMN hora_inicio timestamp(6) with time zone";

    @Test
    void baseNuevaSinTablaReservas_noHaceNadaYNoFalla() {
        String url = BaseDePruebas.crearBase("mig_base_vacia");

        ReservaHoraInicioMigration.Resultado resultado = migracion(url).migrate();

        assertEquals(ReservaHoraInicioMigration.Resultado.SIN_CAMBIOS, resultado);
        assertTrue(BaseDePruebas.consultar(url,
                "SELECT table_name FROM information_schema.tables WHERE table_name = 'Reservas'").isEmpty());
    }

    @Test
    void baseConEsquemaDeLaRama_noHaceNada() {
        String url = BaseDePruebas.crearBase("mig_base_rama");
        BaseDePruebas.ejecutar(url, CREAR_RESERVAS_DE_LA_RAMA);
        BaseDePruebas.ejecutar(url, "INSERT INTO \"Reservas\" (estado_reserva, servicio_reserva, usuario_reserva) "
                + "VALUES (1, 1, 1)");
        List<String> antes = BaseDePruebas.filasDeReservas(url, false);

        ReservaHoraInicioMigration.Resultado resultado = migracion(url).migrate();

        assertEquals(ReservaHoraInicioMigration.Resultado.SIN_CAMBIOS, resultado);
        assertEquals(antes, BaseDePruebas.filasDeReservas(url, false));
        assertNull(BaseDePruebas.nulabilidad(url, "fecha_inicio"));
    }

    @Test
    void esquemaDeMainSinHoraInicio_seOmiteSinTocarLaTabla() {
        String url = BaseDePruebas.crearBase("mig_base_sin_hora");
        BaseDePruebas.aplicarEsquemaDeMain(url);

        ReservaHoraInicioMigration.Resultado resultado = migracion(url).migrate();

        assertEquals(ReservaHoraInicioMigration.Resultado.SIN_CAMBIOS, resultado);
        assertEquals("NO", BaseDePruebas.nulabilidad(url, "fecha_inicio"));
        assertNull(BaseDePruebas.nulabilidad(url, "hora_inicio"));
    }

    @Test
    void esquemaDeMain_rellenaSoloLasNulasConLaFechaLocalYQuitaElNotNull() {
        String url = BaseDePruebas.crearBase("mig_base_main");
        BaseDePruebas.aplicarEsquemaDeMain(url);
        long servicio = BaseDePruebas.insertarDevolviendoId(url, "INSERT INTO \"Servicios\" "
                + "(activo, categoria, duracion, usuario_proveedor, id_recursos, nombre, precio) "
                + "VALUES (true, 'QA', 30, 1, 9001, 'Servicio', 1000) RETURNING id_servicio");
        String insertar = "INSERT INTO \"Reservas\" (fecha_inicio, estado_reserva, usuario_reserva, servicio_reserva) "
                + "VALUES ('%s', 1, 2, " + servicio + ")";
        BaseDePruebas.ejecutar(url, String.format(insertar, "10:00"));
        BaseDePruebas.ejecutar(url, String.format(insertar, "23:30"));
        BaseDePruebas.ejecutar(url, AGREGAR_HORA_INICIO_COMO_HIBERNATE);
        // Fila que ya tenia hora_inicio: la migracion no debe sobrescribirla.
        BaseDePruebas.ejecutar(url, String.format(insertar, "08:00"));
        BaseDePruebas.ejecutar(url, "UPDATE \"Reservas\" SET hora_inicio = '2026-01-01T13:00:00Z' "
                + "WHERE fecha_inicio = '08:00'");

        ReservaHoraInicioMigration.Resultado resultado = migracion(url).migrate();

        assertEquals(new ReservaHoraInicioMigration.Resultado(true, 2, true), resultado);
        // 2026-10-20 (fecha local de la migracion) + hora local de Bogota (UTC-5)
        assertEquals(List.of(
                "1|2026-10-20T15:00:00Z|10:00:00",
                "2|2026-10-21T04:30:00Z|23:30:00",
                "3|2026-01-01T13:00:00Z|08:00:00"), BaseDePruebas.filasDeReservas(url, true));
        assertEquals("YES", BaseDePruebas.nulabilidad(url, "fecha_inicio"));
    }

    @Test
    void ejecutarDosVeces_daElMismoResultado() {
        String url = BaseDePruebas.crearBase("mig_base_repetida");
        BaseDePruebas.aplicarEsquemaDeMain(url);
        long servicio = BaseDePruebas.insertarDevolviendoId(url, "INSERT INTO \"Servicios\" "
                + "(activo, categoria, duracion, usuario_proveedor, id_recursos, nombre, precio) "
                + "VALUES (true, 'QA', 30, 1, 9001, 'Servicio', 1000) RETURNING id_servicio");
        BaseDePruebas.ejecutar(url, "INSERT INTO \"Reservas\" (fecha_inicio, estado_reserva, usuario_reserva, "
                + "servicio_reserva) VALUES ('10:00', 1, 2, " + servicio + ")");
        BaseDePruebas.ejecutar(url, AGREGAR_HORA_INICIO_COMO_HIBERNATE);
        ReservaHoraInicioMigration migracion = migracion(url);

        ReservaHoraInicioMigration.Resultado primera = migracion.migrate();
        List<String> trasPrimera = BaseDePruebas.filasDeReservas(url, true);
        ReservaHoraInicioMigration.Resultado segunda = migracion.migrate();

        assertEquals(new ReservaHoraInicioMigration.Resultado(true, 1, true), primera);
        assertEquals(new ReservaHoraInicioMigration.Resultado(true, 0, false), segunda);
        assertEquals(List.of("1|2026-10-20T15:00:00Z|10:00:00"), trasPrimera);
        assertEquals(trasPrimera, BaseDePruebas.filasDeReservas(url, true));
        assertEquals("YES", BaseDePruebas.nulabilidad(url, "fecha_inicio"));
        assertFalse(segunda.notNullRetirado());
    }

    private ReservaHoraInicioMigration migracion(String url) {
        return new ReservaHoraInicioMigration(new DriverManagerDataSource(url, BaseDePruebas.USER, BaseDePruebas.PASSWORD), RELOJ);
    }
}
