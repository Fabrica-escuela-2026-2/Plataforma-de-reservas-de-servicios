-- Esquema legacy de "Servicios" y "Recursos" anterior a HU-20: "Recursos" solo
-- tiene la llave primaria id_recurso, sin nombre, id_proveedor ni activo.
CREATE TABLE "Servicios" (
    id_servicio bigint NOT NULL,
    activo boolean NOT NULL,
    categoria character varying(255) NOT NULL,
    descripcion character varying(255),
    duracion integer NOT NULL,
    usuario_proveedor bigint NOT NULL,
    id_recursos bigint NOT NULL,
    nombre character varying(255) NOT NULL,
    precio numeric(38,2) NOT NULL
);
ALTER TABLE "Servicios" ALTER COLUMN id_servicio ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE ONLY "Servicios" ADD CONSTRAINT "Servicios_pkey" PRIMARY KEY (id_servicio);

CREATE TABLE "Recursos" (
    id_recurso bigint NOT NULL
);
ALTER TABLE ONLY "Recursos" ADD CONSTRAINT "Recursos_pkey" PRIMARY KEY (id_recurso);
